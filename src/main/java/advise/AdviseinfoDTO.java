package advise;


public class AdviseinfoDTO {
	private int advise_id;
	private int advise_type;
	private String advise_content;
	
	public int getAdvise_id() {
		return advise_id;
	}
	public void setAdvise_id(int advise_id) {
		this.advise_id = advise_id;
	}
	public int getAdvise_type() {
		return advise_type;
	}
	public void setAdvise_type(int advise_type) {
		this.advise_type = advise_type;
	}
	public String getAdvise_content() {
		return advise_content;
	}
	public void setAdvise_content(String advise_content) {
		this.advise_content = advise_content;
	}
	
	
}
